"""Store practice results in the vault: per case score, deal, C vs c_best, replay, vs teammates and records.

    PYTHONPATH=. uv run python proto/practice_report.py [variant] [vault note]
"""

import json
import sys
from datetime import datetime
from pathlib import Path

import httpx

VARIANT = sys.argv[1] if len(sys.argv) > 1 else "A"
NOTE = Path(sys.argv[2] if len(sys.argv) > 2 else
            f"/Users/rxv/Documents/Obsidian/EHL-Hackathon/Progress/Runs/2026-10-10-practice-algorithm-{VARIANT}.md")
RESULTS = Path("proto/runs/variants/results.jsonl")
# Whem's orchestra, best per case after 30 sessions (Team-Knowledge/Plan/Report 2026-10-10 - profile hook and practice A-B)
TEAMMATE = {"case:P01": 0.76, "case:P02": 0.18, "case:P03": 0.83, "case:P04": 0.86, "case:P05": 0.41, "case:P07": 0.70,
            "case:P08": 0.52, "case:P10": 0.66, "case:P11": 0.71, "case:P18": 0.39}


def main():
    rows = [json.loads(l) for l in RESULTS.read_text().splitlines() if l.strip()]
    rows = [r for r in rows if r["variant"] == VARIANT and r["case"].startswith("case:P")]
    try:
        live = {b["case_id"]: b for b in httpx.get("https://arena.tacto.ai/v1/live", timeout=20).json()["bots"]}
    except Exception:
        live = {}
    out = ["---", "tags: [run, practice]", f"updated: {datetime.now():%Y-%m-%d %H:%M}", f"variant: {VARIANT}", "---",
           f"# Practice run: algorithm {VARIANT} on the hosted practice cases", "",
           "Auto-generated by `proto/practice_report.py` from `proto/runs/variants/results.jsonl`. "
           "Algorithm and context: [[../Experiment-Log|Experiment log]] (E16), [[../Teammate-Findings-Comparison|comparison]]. "
           "Teammate = Whem's orchestra best after 30 sessions; record/house = the build page (`/v1/live`) when this note was written.", "",
           "| Case | Type · goal | **Our score** | Teammate best | Record (holder) | House agent | Deal | C_deal vs c_best | Replay |",
           "|---|---|---|---|---|---|---|---|---|"]
    ours, theirs = [], []
    for r in sorted(rows, key=lambda r: r["case"]):
        b = live.get(r["case"], {})
        t = r.get("terms") or {}
        deal = ", ".join(f"{k} {v}" for k, v in t.items() if k in ("unit_price", "payment_days", "contract_months", "effective_date",
                                                                      "lead_time_days", "volume_per_year", "ppm_commitment",
                                                                      "chargeback_eur_per_complaint", "index_clause") and v is not None)
        gap = (f"{r['c_deal']:,.0f} vs {r['c_best']:,.0f} (+{(r['c_deal'] / r['c_best'] - 1) * 100:.1f} %)"
               if r.get("c_deal") and r.get("c_best") else (r.get("error") or "no deal"))
        sc = r["score"] if r["score"] is not None else 0.0
        tm = TEAMMATE.get(r["case"])
        ours.append(sc)
        if tm is not None:
            theirs.append(tm)
        flag = " ✅" if tm is not None and sc > tm else ""
        out.append(f"| {r['case'][5:]} | {b.get('type', '')} | **{sc:.3f}**{flag} | {tm if tm is not None else '–'} | "
                   f"{b.get('best', '–')} ({b.get('holder', '–')}) | {b.get('house', '–')} | {deal or '–'} | {gap} | "
                   f"[replay](https://arena.tacto.ai/replay/{r['session']}) |")
    if ours:
        out += ["", f"**Played {len(ours)} cases. Mean {sum(ours) / len(ours):.3f}** (board points ×100: {sum(ours) / 10 * 100:.1f} "
                f"if these were our best per case over all 10). Teammate mean on the same cases: "
                f"{sum(theirs) / len(theirs):.3f}. ✅ = above the teammate's best."]
    NOTE.parent.mkdir(parents=True, exist_ok=True)
    NOTE.write_text("\n".join(out) + "\n")
    print(f"wrote {NOTE}: {len(ours)} cases")


if __name__ == "__main__":
    main()
