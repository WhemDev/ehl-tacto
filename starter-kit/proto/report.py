"""Write the search results into the Obsidian vault as a Markdown report.

    PYTHONPATH=. uv run python proto/report.py [results.jsonl] [vault note path]

Leaderboard of configs (mean over cases), best per case, and the effect of every setting:
the mean score per value of each knob, per case - which settings help, which hurt.
"""

import json
import sys
from collections import defaultdict
from datetime import datetime
from pathlib import Path

from proto.engine import Config

RESULTS = Path(sys.argv[1] if len(sys.argv) > 1 else "proto/runs/search/results.jsonl")
NOTE = Path(sys.argv[2] if len(sys.argv) > 2 else
            "/Users/rxv/Documents/Obsidian/EHL-Hackathon/Progress/Runs/Search-Results.md")
DEFAULT = Config()


def diff(cfg):
    return ", ".join(f"{k}={v}" for k, v in cfg.items() if getattr(DEFAULT, k, None) != v) or "(default = run 9)"


def main():
    rows = [json.loads(l) for l in RESULTS.read_text().splitlines() if l.strip()]
    played = [r for r in rows if not r.get("control") and r.get("score") is not None]
    controls = [r for r in rows if r.get("control")]
    cases = sorted({r["case"] for r in played})
    by_cfg = defaultdict(dict)
    cfgs = {}
    for r in played:
        by_cfg[r["key"]][r["case"]] = r
        cfgs[r["key"]] = r["cfg"]
    full = [(sum(v[c]["score"] for c in cases) / len(cases), k) for k, v in by_cfg.items() if all(c in v for c in cases)]
    full.sort(reverse=True)
    gens = max(r["gen"] for r in played) if played else 0
    out = [
        "---", "tags: [run, search, generated]", f"updated: {datetime.now():%Y-%m-%d %H:%M}", "---",
        "# Tactic search results (auto-generated)", "",
        f"Generated by `proto/report.py` from `proto/runs/search/results.jsonl`. **Don't edit by hand**: it is rewritten after every generation. "
        f"Context and conclusions: [[../Experiment-Log|Experiment log]].", "",
        f"**{len(played)} sandbox sessions**, {len(by_cfg)} configs, generations 0–{gens}. Cases: {', '.join(cases)}. "
        "Settings not listed in a row are at the default (= run 9: linear concession, T=4, 1 hold, push after final, 3 MESO sheets, warm).", "",
        "## Top 15 configs (mean score over both cases)", "",
        "| # | Mean | " + " | ".join(cases) + " | Gen | Settings that differ from default |",
        "|---|---|" + "---|" * len(cases) + "---|---|",
    ]
    for i, (m, k) in enumerate(full[:15], 1):
        v = by_cfg[k]
        out.append(f"| {i} | **{m:.3f}** | " + " | ".join(f"{v[c]['score']:.3f}" for c in cases)
                   + f" | {min(v[c]['gen'] for c in cases)} | {diff(cfgs[k])} |")
    out += ["", "## Best per case (a config can be picked per case type)", ""]
    for c in cases:
        best = max((v[c] for v in by_cfg.values() if c in v), key=lambda r: r["score"])
        t = best.get("terms") or {}
        out.append(f"- **{c}: {best['score']:.3f}** (C {best['c_deal']:,.0f} vs c_best {best['c_best']:,.0f}), "
                   f"deal {t.get('unit_price')} {t.get('incoterm') or ''} {t.get('payment_days')}d, session `{best['session']}`. "
                   f"Settings: {diff(best['cfg'])}")
    out += ["", "## Effect of each setting", "",
            "Mean score of all configs that used this value (n = sessions). A big spread between values = the setting matters. "
            "Random configs change many settings at once, so treat this as a hint, not proof.", ""]
    for knob in [f for f in DEFAULT.__dataclass_fields__ if f != "max_rounds"]:
        vals = defaultdict(lambda: defaultdict(list))
        for r in played:
            vals[json.dumps(r["cfg"].get(knob))][r["case"]].append(r["score"])
        if len(vals) < 2:
            continue
        out.append(f"**{knob}**")
        out.append("")
        out.append("| Value | " + " | ".join(cases) + " |")
        out.append("|---|" + "---|" * len(cases))
        for val, per in sorted(vals.items()):
            out.append(f"| `{val}` | " + " | ".join(
                f"{sum(per[c]) / len(per[c]):.3f} (n={len(per[c])})" if per[c] else "–" for c in cases) + " |")
        out.append("")
    if controls:
        out += ["## Determinism controls", "",
                "Each generation replays the current best config once. Same score = the sandbox suppliers are deterministic.", ""]
        for r in controls:
            orig = by_cfg.get(r["key"], {}).get(r["case"])
            same = orig and abs(orig["score"] - r["score"]) < 1e-9
            out.append(f"- gen {r['gen']} {r['case']}: replay {r['score']:.4f} vs first {orig['score']:.4f} → "
                       + ("identical ✅" if same else "**different** ⚠️") if orig else f"- gen {r['gen']} {r['case']}: {r['score']}")
    NOTE.parent.mkdir(parents=True, exist_ok=True)
    NOTE.write_text("\n".join(out) + "\n")
    print(f"wrote {NOTE} ({len(played)} sessions, {len(full)} complete configs)")


if __name__ == "__main__":
    main()
